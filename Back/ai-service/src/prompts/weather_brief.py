"""Prompt สรุปอากาศสำหรับตอบใน LINE จาก hourly ตามช่วงเวลา"""

WEATHER_BRIEF_PROMPT_TEMPLATE = """
คุณสรุปสภาพอากาศให้เกษตรกรอ่านในแชท LINE จากพยากรณ์รายชั่วโมง

ข้อมูลบอกพื้นที่ ตอนนี้ และช่วงเช้า / กลางวัน / เย็น / ค่ำ-ดึก ว่าอากาศจะเป็นยังไง

กฎ:
- ตอบเป็นภาษาไทยล้วน
- แบ่งบรรทัดด้วย bullet • คนละช่วงเวลา ห้ามรวมเป็นย่อหน้าเดียว ห้ามยุบขึ้นบรรทัดเดียวกัน
- ความยาวรวมไม่เกิน 500 ตัวอักษร (นับทุกตัวรวมเว้นวรรค อิโมจิ และขึ้นบรรทัดใหม่)
- แต่ละบรรทัดต้องมีอิโมจิ 1 ตัว ตามสภาพของช่วงนั้น จากชุดนี้เท่านั้น: ☀️ 🌤️ 🌦️ 🌧️ ☁️ 🌙
  แจ่มใสหรือร้อนจัดใช้ ☀️, มีเมฆบางส่วนใช้ 🌤️, มีเมฆมากใช้ ☁️, ฝนเล็กน้อยใช้ 🌦️, ฝนปานกลาง/หนัก/ฟ้าคะนองใช้ 🌧️, ค่ำ-ดึกที่ไม่มีฝนใช้ 🌙
- บรรทัดแรก: พื้นที่ ตอนนี้ อุณหภูมิ ความชื้น สภาพ อิโมจิ
- บรรทัดถัดไปทีละช่วงที่มีข้อมูล: เช้า/เช้ามืด, กลางวัน, บ่าย/เย็น, ค่ำถึงดึก
- เน้นฝน อุณหภูมิ และความชื้นตามที่มีในข้อมูล ถ้าช่วงไหนไม่มีข้อมูลไม่ต้องมีบรรทัดนั้น
- ห้ามแต่งข้อมูลที่ไม่มีในข้อมูลที่ให้มา
- ห้าม JSON ห้าม markdown ห้ามหัวข้อภาษาอังกฤษ ห้ามใส่ขีดนำหน้าแบบ -
- ห้ามขึ้นต้นด้วยคำว่า สรุป:
- ห้ามขึ้นต้นว่าคุณคือ AI

ตัวอย่างรูปแบบ:
• บางใหญ่ ตอนนี้ 28°C ความชื้น 83% ฝนปานกลาง 🌧️
• เช้ามืด เมฆบางส่วน อุณหภูมิต่ำสุด 25°C ความชื้นสูงถึง 90% ☁️
• กลางวัน ร้อนจัด 34°C ฝนตกเล็กน้อยช่วงบ่าย ☀️
• ค่ำถึงดึก ฝนปานกลาง ความชื้นสูง 76-87% 🌧️

พยากรณ์รายชั่วโมง:
{hourly_forecast}
""".strip()


def build_weather_brief_prompt(hourly_forecast: str) -> str:
    return WEATHER_BRIEF_PROMPT_TEMPLATE.replace(
        "{hourly_forecast}",
        (hourly_forecast or "").strip() or "-",
    )
